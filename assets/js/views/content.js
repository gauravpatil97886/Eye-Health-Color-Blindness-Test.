function section(heading, body, ...extra) {
  return h('div.stack.stack--sm',
    h('h2', { style: { fontSize: 'var(--text-xl)' } }, heading),
    body && h('p.muted', { style: { maxWidth: 'var(--measure)' } }, body),
    ...extra);
}
